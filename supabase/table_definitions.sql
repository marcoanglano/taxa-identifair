-- =============================================================================
-- DATABASE SCHEMA: TAXA IDENTIFAIR (v1.0.0)
-- Target Domain: marine Zooplankton (Copepoda: Calanoida)
-- Notes: supports client-side caching, dimorphism (F/M), and asymmetric traits.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- TABLES & VIEWS
-- -----------------------------------------------------------------------------

-- 1. METADATA & DATASET VERSIONING (system release versions, Schema.org FAIR dataset metadata, DOIs.)
create table public.app_metadata (
  key text not null,                                                                  -- es. 'active_release'
  data_version integer not null default 1,                                            -- es. 1
  updated_at timestamp with time zone null default now(),
  schema_version character varying(20) not null default '1.0.0'::character varying,   -- es. '1.0.0'
  dataset_version character varying(20) not null default '1.0.0'::character varying,  -- es. '1.0.0'
  doi character varying(255) null,                                                    -- es. '10.6084/m9.figshare.34956271'
  release_date timestamp with time zone not null default now(),
  changelog text null,                                                                -- es. 'First release'
  constraint app_metadata_pkey primary key (key)
) TABLESPACE pg_default;

-- 2. CONTEXTUAL FILTERS (Ecology & Dimensions)
create table public.filters (
  id_species text not null,                                                           -- es. 'anomalocera_patersonii'
  environment text[] not null default '{}'::text[],                                   -- es. ['marine', 'brackish']
  f_min numeric(5, 3) null,                                                           -- es. '3.000'
  f_max numeric(5, 3) null,                                                           -- es. '3.000'
  m_min numeric(5, 3) null,                                                           -- es. '3.000'
  m_max numeric(5, 3) null,                                                           -- es. '3.000'
  constraint filters_pkey primary key (id_species),
  constraint filters_id_species_fkey foreign KEY (id_species) references species (id_species) on delete CASCADE
) TABLESPACE pg_default;
create index IF not exists idx_filters_environment_gin on public.filters using gin (environment) TABLESPACE pg_default;

-- 3. SPECIES (Taxonomy & External Identifiers)
create table public.species (
  id_species text not null primary key,                                               -- es. 'anomalocera_patersonii'
  gbif_key integer not null,                                                          -- es. '5166357'
  gbif_link text null,                                                                -- es. '676T9'
  aphia_id integer null,                                                              -- es. '364368'
  other_id integer null,                                                              -- es. '1184'
  family text not null,                                                               -- es. 'Pontellidae'
  genus text not null,                                                                -- es. 'Anomalocera'
  scientific_name text not null,                                                      -- es. 'Anomalocera patersonii'
  authority text null,                                                                -- es. 'Templeton, 1837'
  created_at timestamp with time zone not null default now(),
  constraint species_pkey primary key (id_species)
) TABLESPACE pg_default;
create index IF not exists idx_species_taxonomy on public.species using btree (family, genus) TABLESPACE pg_default;

-- 4. SPECIES REFERENCES (references of species drawings)
create table public.species_references (
  id bigint generated by default as identity not null,                                -- es. 1
  id_species text not null,                                                           -- es. 'anomalocera_patersonii'
  citation text not null,                                                             -- es. '<b>Giesbrecht</b>, [...]'
  created_at timestamp with time zone null default now(),
  constraint species_references_pkey primary key (id),
  constraint species_references_id_species_fkey foreign KEY (id_species) references species (id_species) on delete CASCADE
) TABLESPACE pg_default;
create index IF not exists idx_species_references_sp on public.species_references using btree (id_species) TABLESPACE pg_default;

-- 5. SPECIES TRAITS (Sexual dimorphism & Side indipendently from sex)
create table public.species_traits (
  id_species text not null,                                                           -- es. 'anomalocera_patersonii'
  id_trait text not null,                                                             -- es. 'PR_frsh'
  -- FEMALE STATE (♀) by side
  f_left_states text[] not null default '{}'::text[],                                 -- es. 'PR_frsh_ro'
  f_right_states text[] not null default '{}'::text[],                                -- leave empty if symmetric trait
  f_notes text null,                                                                  -- es. 'Subtriangular front.'
  f_notes_url text null,                                                              -- link of drawing
  -- MALE STATE (♂) by side
  m_left_states text[] not null default '{}'::text[],                                 -- es. 'PR_frsh_ro'
  m_right_states text[] not null default '{}'::text[],                                -- leave empty if symmetric trait
  m_notes text null,                                                                  -- es. 'Subtriangular front.'
  m_notes_url text null,                                                              -- link of drawing
  created_at timestamp with time zone not null default now(),
  constraint species_traits_pkey primary key (id_species, id_trait),
  constraint species_traits_id_species_fkey foreign KEY (id_species) references species (id_species) on delete CASCADE,
  constraint species_traits_id_trait_fkey foreign KEY (id_trait) references traits (id_trait) on delete CASCADE
) TABLESPACE pg_default;
create index IF not exists idx_species_traits_f_left on public.species_traits using gin (f_left_states) TABLESPACE pg_default;
create index IF not exists idx_species_traits_f_right on public.species_traits using gin (f_right_states) TABLESPACE pg_default;
create index IF not exists idx_species_traits_m_left on public.species_traits using gin (m_left_states) TABLESPACE pg_default;
create index IF not exists idx_species_traits_m_right on public.species_traits using gin (m_right_states) TABLESPACE pg_default;
create trigger tr_bump_matrix_version
after INSERT
or DELETE
or
update on species_traits for EACH STATEMENT
execute FUNCTION bump_matrix_version ();

-- 6. TRAIT STATES (Trait values that can be selected)
create table public.trait_states (
  id_trait text not null,                                                             -- es. 'PR_frsh'
  id_state text not null,                                                             -- es. 'PR_frsh_ro'
  state_label text not null,                                                          -- es. 'Rounded'
  sort_order integer null,                                                            -- es. 1
  state_icon_url text null,                                                           -- icon url
  created_at timestamp with time zone not null default now(),
  constraint trait_states_pkey primary key (id_trait, id_state),
  constraint trait_states_id_trait_fkey foreign KEY (id_trait) references traits (id_trait) on delete CASCADE
) TABLESPACE pg_default;
create index IF not exists idx_trait_states_order on public.trait_states using btree (id_trait, sort_order) TABLESPACE pg_default;

-- 7. TRAITS (Anatomy, Asimmetries & Hierarchies)
create table public.traits (
  id_trait text not null,                                                             -- es. 'PR_frsh'
  trait_category text not null,                                                       -- es. 'Prosome (PR)'
  trait_name text not null,                                                           -- es. 'Front shape'
  description text not null,                                                          -- es. 'Shape of the prosome front [...]'
  description_url text null,                                                          -- es. Explanatory drawing url
  trait_icon_url text null,                                                           -- es. Icon url
  can_be_asymmetric boolean not null default false,                                   -- Asymmetry flag
  parent_trait_id text null,                                                          -- Trait hierarchy
  required_state_id text null,                                                        -- Required to unlock child trait
  created_at timestamp with time zone not null default now(),
  constraint traits_pkey primary key (id_trait),
  constraint traits_parent_trait_id_fkey foreign KEY (parent_trait_id) references traits (id_trait) on delete set null
) TABLESPACE pg_default;
create index IF not exists idx_traits_parent on public.traits using btree (parent_trait_id) TABLESPACE pg_default;

