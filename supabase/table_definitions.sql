-- 1. bump_matrix_version (trigger function)
-- Automatically increments the data version upon any update to species traits.
-- Used by client applications to trigger incremental sync or clear IndexedDB.
begin
  update public.app_metadata 
  set data_version = data_version + 1, updated_at = now()
  where key = 'identification_matrix';
  return null;
end;
