-- 9. VISTA FOR CLIENT-SIDE DOWNLOAD (Completo Denormalized JSON)
-- SELECT * FROM public.v_identification_matrix to download the full database.
create view public.v_identification_matrix as
select
  s.id_species,
  s.scientific_name,
  s.family,
  f.environment,
  f.f_min,
  f.f_max,
  f.m_min,
  f.m_max,
  COALESCE(
    jsonb_agg(
      jsonb_build_object(
        'id_trait',
        st.id_trait,
        'f_left',
        st.f_left_states,
        'f_right',
        st.f_right_states,
        'f_notes',
        st.f_notes,
        'f_notes_url',
        st.f_notes_url,
        'm_left',
        st.m_left_states,
        'm_right',
        st.m_right_states,
        'm_notes',
        st.m_notes,
        'm_notes_url',
        st.m_notes_url
      )
    ) filter (
      where
        st.id_trait is not null
    ),
    '[]'::jsonb
  ) as traits
from
  species s
  left join filters f on s.id_species = f.id_species
  left join species_traits st on s.id_species = st.id_species
group by
  s.id_species,
  s.scientific_name,
  s.family,
  f.environment,
  f.f_min,
  f.f_max,
  f.m_min,
  f.m_max;


